export function isGuestMode(): boolean {
  try {
    const stored = localStorage.getItem('simplicadet_guest_session');
    if (stored) {
      const session = JSON.parse(stored);
      return session.expiresAt && new Date(session.expiresAt) > new Date();
    }
  } catch {
  }
  return false;
}
export function getDemoDataIfGuest<T>(realData: T[], demoData: T[]): T[] {
  return isGuestMode() ? demoData : realData;
}
